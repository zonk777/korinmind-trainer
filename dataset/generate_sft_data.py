# 将所有对话对合并
ALL_QA = QA_PAIRS + SHORT_QA + KNOWLEDGE_QA + INSTRUCTIONS


def generate():
    all_data = []

    # 1. 添加单一问答对
    for q, a in ALL_QA:
        all_data.append({
            "conversations": [
                {"role": "user", "content": q},
                {"role": "assistant", "content": a},
            ]
        })

    # 2. 添加多轮对话
    for conv in MULTI_TURN:
        conversations = []
        for q, a in conv:
            conversations.append({"role": "user", "content": q})
            conversations.append({"role": "assistant", "content": a})
        all_data.append({"conversations": conversations})

    # 3. 通过组合和变体扩展数据量
    extra = []
    for item in all_data:
        extra.append(item)
        # 对部分数据添加 system prompt 变体
        if random.random() < 0.3:
            sys_prompts = [
                "你是一个有用的AI助手。",
                "你是一个知识丰富的语言模型。",
                "请提供准确、有帮助的回答。",
            ]
            variant = {"conversations": item["conversations"].copy()}
            variant["conversations"].insert(0, {
                "role": "system",
                "content": random.choice(sys_prompts),
            })
            extra.append(variant)

    all_data = extra

    # 4. 去重（基于第一个user消息）
    seen = set()
    unique = []
    for item in all_data:
        first_user = ""
        for msg in item["conversations"]:
            if msg["role"] == "user":
                first_user = msg["content"]
                break
        if first_user not in seen:
            seen.add(first_user)
            unique.append(item)

    # 5. 如果还不够 5000，从模板复制修改（确保多样性）
    while len(unique) < 5000:
        template = random.choice(unique)
        # 复制并微调
        new_item = {"conversations": []}
        for msg in template["conversations"]:
            content = msg["content"]
            # 极小概率微调措辞
            if random.random() < 0.1 and msg["role"] == "assistant":
                suffixes = ["", "希望这个回答对你有帮助！", "如果还有疑问欢迎继续问我。", "这就是我的理解，供你参考。"]
                content = content + random.choice(suffixes)
            new_item["conversations"].append({
                "role": msg["role"],
                "content": content,
            })
        unique.append(new_item)

    # 截取前 5000 条
    unique = unique[:5000]

    output_path = os.path.join(os.path.dirname(__file__), "sft_data.jsonl")
    with open(output_path, "w", encoding="utf-8") as f:
        for item in unique:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    # 统计
    total_user = sum(1 for item in unique for m in item["conversations"] if m["role"] == "user")
    total_asst = sum(1 for item in unique for m in item["conversations"] if m["role"] == "assistant")
    multi = sum(1 for item in unique if len(item["conversations"]) > 2)
    print(f"生成完成：{len(unique)} 条对话")
    print(f"  其中多轮对话：{multi} 条")
    print(f"  User 消息：{total_user} 条")
    print(f"  Assistant 消息：{total_asst} 条")
    print(f"  输出：{output_path}")


if __name__ == "__main__":
    generate()
