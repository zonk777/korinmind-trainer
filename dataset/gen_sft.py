all_data = []
for q, a in qa:
    all_data.append({"conversations": [{"role": "user", "content": q}, {"role": "assistant", "content": a}]})

for conv in multi:
    conversations = []
    for q, a in conv:
        conversations.append({"role": "user", "content": q})
        conversations.append({"role": "assistant", "content": a})
    all_data.append({"conversations": conversations})

n_base = len(all_data)
while len(all_data) < 5000:
    template = random.choice(all_data[:n_base])
    all_data.append({"conversations": template["conversations"].copy()})

all_data = all_data[:5000]
random.shuffle(all_data)

with open("dataset/sft_data.jsonl", "w", encoding="utf-8") as f:
    for item in all_data:
        f.write(json.dumps(item, ensure_ascii=False) + "\n")

